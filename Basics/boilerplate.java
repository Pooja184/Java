// This is a basic Java program that prints "Hello, World!" to the console.
// The class name must match the file name (boilerplate.java).
public class boilerplate {
    public static void main(String[] args) { // The main method is the entry point of the program.
        System.out.println("Hello, World!");// here we can also use \n for new line
        System.out.print("Print output on the same line. ");
    }
}   

